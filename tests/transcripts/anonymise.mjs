// Turns a slice of a real saved conversation into a fixture with none of its words: every text
// becomes a marker of the same length (<<pad:N>>, put back as filler by the tests), and what is
// left out becomes filler too, so each line keeps its length, type, tool calls, times and
// background-task notices: what decides how much of a conversation one read takes in.
//   node anonymise.mjs <transcript.jsonl> <from ISO> <to ISO> [--say <ISO>=<text>]... > lines.json
// --say gives the line written at that time a text of your own (a request, a final reply).
import { readFileSync } from 'node:fs'

const [path, from, to, ...rest] = process.argv.slice(2)
const say = {}
for (let i = 0; i < rest.length; i++) if (rest[i] === '--say') { const [at, ...t] = rest[++i].split('='); say[at] = t.join('=') }
const pad = (s) => `<<pad:${JSON.stringify(String(s ?? '')).length - 2}>>`
const notice = (s) => {
  const tag = (k) => /<(\w[\w-]*)>([^<]*)<\/\1>/.test(s) ? new RegExp(`<${k}>([^<]*)</${k}>`).exec(s)?.[1] : undefined
  const parts = ['task-id', 'tool-use-id', 'status'].filter((k) => tag(k) !== undefined).map((k) => `<${k}>${tag(k)}</${k}>`)
  return `<task-notification>\n${parts.join('\n')}\n</task-notification>`
}
const text = (t, at) => (say[at] !== undefined ? say[at] : /<task-notification>/.test(t) ? notice(t) : pad(t))
let step = 0
const out = []
for (const raw of readFileSync(path, 'utf8').split('\n')) {
  let d
  try { d = JSON.parse(raw) } catch { continue }
  const at = d.timestamp
  if (!at || at < from || at > to) continue
  if (!['user', 'assistant', 'attachment'].includes(d.type)) continue
  const o = { type: d.type, timestamp: at }
  for (const k of ['isSidechain', 'isMeta', 'isCompactSummary']) if (d[k]) o[k] = d[k]
  if (d.message) {
    const c = d.message.content
    const m = { role: d.message.role }
    if (d.message.stop_reason) m.stop_reason = d.message.stop_reason
    m.content = typeof c === 'string' ? text(c, at) : (c ?? []).map((b) => {
      if (b.type === 'text') return { type: 'text', text: text(b.text, at) }
      if (b.type === 'thinking') return { type: 'thinking', thinking: b.thinking ? pad(b.thinking) : '' }
      if (b.type === 'tool_use') {
        const input = { description: 'Step ' + ++step }
        if (typeof b.input?.command === 'string') input.command = 'command ' + step
        if (b.input?.run_in_background) input.run_in_background = true
        return { type: 'tool_use', id: b.id, name: b.name, input }
      }
      if (b.type === 'tool_result') {
        const inner = typeof b.content === 'string' ? b.content : (b.content ?? []).map((x) => x.text ?? '').join('')
        return { type: 'tool_result', tool_use_id: b.tool_use_id, content: pad(inner) }
      }
      if (b.type === 'image') return { type: 'text', text: pad('image') }
      return { type: b.type }
    })
    o.message = m
  }
  const r = d.toolUseResult
  if (r && typeof r === 'object') {
    const keep = {}
    for (const k of ['backgroundTaskId', 'status', 'isAsync', 'taskId', 'agentId']) if (r[k] !== undefined) keep[k] = r[k]
    if (typeof r.stdout === 'string') keep.stdout = pad(r.stdout)
    o.toolUseResult = keep
  }
  if (d.attachment) {
    const a = d.attachment
    const p = Array.isArray(a.prompt) ? a.prompt.map((b) => b?.text ?? '').join('') : a.prompt
    o.attachment = { type: a.type, ...(a.commandMode ? { commandMode: a.commandMode } : {}), ...(p !== undefined ? { prompt: text(p, at) } : {}) }
  }
  // What was left out (ids, versions, signatures, tool inputs) as filler, so the line keeps its length
  const need = raw.length - JSON.stringify(o).length - ',"fill":""'.length
  if (need > 0) o.fill = `<<pad:${need}>>`
  out.push(JSON.stringify(o))
}
process.stdout.write('// Generated by anonymise.mjs from a real conversation: every text is a same-length marker\nexport default ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + '\n')
